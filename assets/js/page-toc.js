/**
 * Build the optional "On this page" table of contents.
 *
 * Expected HTML, created by _includes/table-of-contents.html:
 *   <aside class="page-toc" data-min-headings="3">
 *     <nav id="page-toc-list"></nav>
 *   </aside>
 *
 * Styling hooks live in assets/css/style.scss:
 *   .page-toc, .page-toc.is-ready, .page-toc__link, .is-active
 */
document.addEventListener("DOMContentLoaded", function () {
  // The outer TOC container and the empty list that will receive generated links.
  const toc = document.querySelector(".page-toc");
  const tocList = document.querySelector("#page-toc-list");

  // Stop quietly on pages where the include is absent, for example toc: false pages.
  if (!toc || !tocList) {
    return;
  }

  // Liquid writes data-min-headings into HTML; fall back to 3 if it is missing.
  const minHeadings = Number.parseInt(toc.dataset.minHeadings || "3", 10);

  // Collect h2/h3/h4 headings from the main content column only.
  // Exclude headings that might appear inside navigation, footer, or TOC regions.
  const headings = Array.from(
    document.querySelectorAll(".main-content h4, .main-content h2, .main-content h3")
  ).filter(function (heading) {
    return !heading.closest(
      ".page-toc, .prev-next, .site-footer-custom, .page-breadcrumb"
    );
  });

  // If the page is short, remove the unused TOC shell instead of showing clutter.
  if (headings.length < minHeadings) {
    toc.remove();
    return;
  }

  // Create one TOC link for each collected heading.
  headings.forEach(function (heading) {
    // Headings generated by Markdown usually have ids, but raw HTML headings might not.
    if (!heading.id) {
      heading.id = heading.textContent
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");
    }

    // The href begins with "#" because TOC links jump to an id on the same page.
    // For example, heading.id "main-idea" becomes href "#main-idea".
    // The h2/h3 modifier class lets SCSS style heading levels differently.
    const link = document.createElement("a");
    link.href = "#" + heading.id;
    link.textContent = heading.textContent;
    link.className =
      "page-toc__link page-toc__link--" + heading.tagName.toLowerCase();
    tocList.appendChild(link);
  });

  // Reveal the TOC only after links have been created.
  toc.classList.add("is-ready");

  // Older browsers still get a usable TOC, but without active-section highlighting.
  if (!("IntersectionObserver" in window)) {
    return;
  }

  // Map heading ids to their matching TOC links for quick lookup during scroll.
  const linksById = new Map(
    Array.from(tocList.querySelectorAll("a")).map(function (link) {
      return [link.getAttribute("href").slice(1), link];
    })
  );

  // Watch headings as they pass through the upper part of the viewport.
  const observer = new IntersectionObserver(
    function (entries) {
      entries.forEach(function (entry) {
        const link = linksById.get(entry.target.id);
        if (!link) {
          return;
        }

        if (entry.isIntersecting) {
          // Keep exactly one generated TOC link marked as the active section.
          tocList.querySelectorAll(".is-active").forEach(function (activeLink) {
            activeLink.classList.remove("is-active");
          });
          link.classList.add("is-active");
        }
      });
    },
    // This root margin makes the active link update near the top of the reading area.
    { rootMargin: "-15% 0px -70% 0px", threshold: 0 }
  );

  // Start observing every heading that appears in the generated TOC.
  headings.forEach(function (heading) {
    observer.observe(heading);
  });
});
